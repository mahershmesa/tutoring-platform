-- =============================================================
-- 20260802090018_backfill_message_recipient.sql
-- تعبئة رجعية لـ recipient_id للرسائل القديمة (قبل migration 17).
--
-- الأثر: رسائل المدرّسين القديمة كانت recipient_id = NULL، فصارت مخفية بعد
-- تشديد الخصوصية 1-إلى-1 → زر "أكّد استلام الرد" لا يظهر → العدّاد لا يتحرّك.
--
-- نعبّئ ما نستطيع تحديده بثقة:
--   * رسالة أرسلها المدرّس (المرسِل ليس صاحب السؤال) → المستقبِل هو صاحب السؤال.
-- (رسائل الطالب القديمة كانت تُبَثّ ولا نعرف المدرّس المقصود؛ نتركها — لا تؤثر
--  على ظهور رد المدرّس ولا على العدّاد.)
-- =============================================================

update public.messages m
set recipient_id = q.student_id
from public.questions q
where m.question_id = q.id
  and m.recipient_id is null
  and m.sender_id <> q.student_id;
